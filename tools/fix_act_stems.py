#!/usr/bin/env python3
"""Stop ACT passage questions repeating the passage inside the stem.

40.7% of ACT items with a passage carried most of that passage a second time
in the stem, so a student read the same paragraphs twice and found the real
question at the bottom. Emma saw it on the Reading screen and said the
questions "make no sense", which is exactly right: the question was buried.

Two shapes, and they do NOT get the same treatment.

READING  the stem is passage prose followed by the question. The prose is
         pure duplication; keep the tail.

ENGLISH  the stem is passage prose, then the sentence under consideration
         wrapped in <u>, then "the writer is considering deleting the
         underlined sentence...". The underline is load-bearing - delete it
         and the question has no referent. The real paper marks it IN the
         passage and lets the question point at it, so that is what we do:
         move the <u> onto the passage, then keep the tail.

Anything that will not reduce to a plausible question is left exactly as it
is. A wrong fix here silently destroys a question, which is far worse than
leaving a visible duplicate that we can see and fix later.
"""
import argparse, glob, json, re

SENT = re.compile(r'(?<=[.!?"])\s+')
U = re.compile(r'<u>(.*?)</u>', re.S)
# A stem is a question or a stem-completion. The ACT uses both, and the
# colon form - "The first paragraph is chiefly concerned with explaining that
# repair cafes:" - is as common as the question mark. Requiring a '?' threw
# out 141 perfectly ordinary Reading stems.
ASKS = re.compile(
    r'[?:]\s*$'
    r'|^(which|what|the writer|the author|suppose|as used|according to)',
    re.I)


def norm(t):
    return ' '.join((t or '').split())


def plain(t):
    """Normalised text with the markup taken out.

    Detection has to ignore tags. The first pass compared the raw stem
    against the passage, so an English item whose stem opens with
    "The project required <u>patience, ..." never matched - the literal
    "<u>" is not in the passage - and 160 questions that duplicate the
    passage were skipped as if they were clean.
    """
    return norm(re.sub(r'<[^>]+>', '', t or ''))


def mark_in_passage(stim, phrase):
    """Underline `phrase` inside the passage, once, if it is there plainly."""
    if '<u>' in stim and phrase in U.findall(stim):
        return stim                                    # already marked
    i = stim.find(phrase)
    if i < 0:
        return None
    return stim[:i] + '<u>' + phrase + '</u>' + stim[i + len(phrase):]


def reduce_stem(stim, stem):
    """The question at the end of a stem that starts as passage prose.

    Tags come off BEFORE the sentence split. With them on, "...science.</u>
    The writer is considering..." has no split point - the lookbehind sees
    the `>` and not the full stop - so the underlined sentence and the
    question fused into one part, failed the in-passage test, and the
    sentence survived into the stem it had just been moved out of.
    """
    s_norm = plain(stim)
    parts = SENT.split(plain(stem))
    keep = 0
    for i, part in enumerate(parts):
        core = part.strip()
        if len(core) > 40 and core in s_norm:
            keep = i + 1
        else:
            break
    if not keep:
        return None
    tail = ' '.join(parts[keep:]).strip()
    if len(tail) < 15 or not ASKS.search(tail):
        return None
    return tail


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--write', action='store_true')
    ap.add_argument('--path', default='data/act/questions.json',
                    help='the SOURCE bank. data/act/q/*.json is generated by '
                         'split_bank.py, so fixing it there is undone by the '
                         'next build.')
    args = ap.parse_args()

    seen = fixed = marked = left = 0
    samples = []
    for path in sorted(glob.glob(args.path)):
        doc = json.load(open(path))
        items = doc.get('items', doc) if isinstance(doc, dict) else doc
        dirty = False
        for it in items:
            stim, stem = it.get('stimulus'), it.get('stem')
            if not stim or not stem or len(plain(stem)) <= 200:
                continue
            if plain(stem)[:150] not in plain(stim):
                continue
            seen += 1

            new_stim = stim
            # Move any underline in the stem onto the passage first, so the
            # tail is still anchored to something the student can see.
            for phrase in U.findall(norm(stem)):
                moved = mark_in_passage(norm(new_stim), norm(phrase))
                if moved is None:
                    new_stim = None
                    break
                new_stim = moved
            if new_stim is None:
                left += 1
                continue

            tail = reduce_stem(stim, stem)
            if tail is None:
                left += 1
                continue

            # The tail still refers to "the underlined sentence", so strip the
            # markup out of the question itself - it lives on the passage now.
            tail_plain = U.sub(r'\1', tail).strip()
            if not ASKS.search(tail_plain):
                left += 1
                continue

            if len(samples) < 3:
                samples.append((it['id'], it.get('section'),
                                len(norm(stem)), tail_plain))
            if args.write:
                it['stem'] = tail_plain
                if new_stim != stim:
                    it['stimulus'] = new_stim
                    marked += 1
                dirty = True
            elif new_stim != stim:
                marked += 1
            fixed += 1
        if args.write and dirty:
            json.dump(doc, open(path, 'w'), indent=1, ensure_ascii=False)

    print(f'{seen} stems repeat the passage')
    print(f'  {fixed} reduced to the question')
    print(f'  {marked} also had an underline moved onto the passage')
    print(f'  {left} left alone (would not reduce safely)')
    for qid, sec, was, now in samples:
        print(f'\n  {qid} [{sec}] {was} chars -> {len(now)}')
        print(f'    {now}')
    if not args.write:
        print('\nDRY RUN - nothing written. Re-run with --write.')


if __name__ == '__main__':
    main()
