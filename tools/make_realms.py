#!/usr/bin/env python3
"""Cut the six realm islands out of the design board, and find their land.

The board's bottom row carries one island map per section, drawn in that
section's own palette and - unlike the big realm panels higher up - with no
lettering on the map itself. That makes them the right plate for the land
level: six boards unique to each section, where before every land opened on
a photograph and every one of them shared a single inner map.

Swapping the plate invalidates the hotspots, because the coordinates in
places.ts were read off photographs. Rather than author twenty-six new
points by eye on a 228px tile, this finds them: the islands are bright
land on dark water, so a mask plus a distance transform gives the points
furthest from any shoreline, and a greedy pick keeps them apart. A chapter
then stands on land rather than in the sea, which is the only thing the
coordinates have to get right.
"""
import argparse, json, os, sys

import numpy as np
from PIL import Image, ImageFilter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SHEET = os.path.join(ROOT, "assets", "sheets", "realm-of-knowledge.webp")
OUT = os.path.join(ROOT, "apps", "web", "public", "art", "realms")

# The row, measured off the board. Left to right.
PITCH = 253.8
X0, INSET, WIDTH = 12, 12, 214
Y1, Y2 = 498, 610
SCALE = 6

# Which island is which land, by this app's terrain names.
ORDER = ["ocean", "cliffs", "peaks", "tropic", "fair", "park"]
TITLES = {
    "ocean": "SAT English", "cliffs": "SAT Math", "peaks": "ACT English",
    "tropic": "ACT Math", "fair": "ACT Reading", "park": "ACT Science",
}
# How many hotspots each land needs: its chapter count, with headroom.
WANT = 8


def land_mask(im: Image.Image) -> np.ndarray:
    """True where the picture is island rather than sea.

    Brightness alone is not enough - the violet realm's water glows - so
    this also takes saturation, which the drawn land has and the flat sea
    mostly does not.
    """
    a = np.asarray(im.convert("RGB"), dtype=np.float32) / 255
    mx, mn = a.max(2), a.min(2)
    val = mx
    sat = (mx - mn) / np.maximum(mx, 1e-6)
    score = val * 0.68 + sat * 0.32
    return score > np.quantile(score, 0.56)


def distance_inside(mask: np.ndarray) -> np.ndarray:
    """Crude distance transform: how far each land pixel is from water.

    Iterated erosion rather than scipy, because this project does not carry
    scipy and eight passes is plenty at this size.
    """
    d = mask.astype(np.float32)
    cur = mask.copy()
    for _ in range(14):
        e = cur.copy()
        e[1:, :] &= cur[:-1, :]
        e[:-1, :] &= cur[1:, :]
        e[:, 1:] &= cur[:, :-1]
        e[:, :-1] &= cur[:, 1:]
        cur = e
        d += cur
    return d


def pick(d: np.ndarray, n: int, apart: float) -> list[tuple[float, float]]:
    """The n deepest-inland points that are not on top of each other."""
    h, w = d.shape
    flat = np.argsort(d, axis=None)[::-1]
    out: list[tuple[float, float]] = []
    for idx in flat:
        if len(out) == n:
            break
        y, x = divmod(int(idx), w)
        if d[y, x] <= 1:
            break
        # Keep clear of the very edge: a label there leaves the frame.
        if not (0.07 * w < x < 0.93 * w and 0.12 * h < y < 0.88 * h):
            continue
        if any((x - px) ** 2 + (y - py) ** 2 < apart ** 2 for px, py in out):
            continue
        out.append((x, y))
    return [(round(x / w * 100, 1), round(y / h * 100, 1)) for x, y in out]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    args = ap.parse_args()

    board = Image.open(SHEET).convert("RGB")
    anchors: dict[str, list[tuple[float, float]]] = {}
    sizes: dict[str, tuple[int, int]] = {}

    for i, terrain in enumerate(ORDER):
        left = int(X0 + i * PITCH) + INSET
        tile = board.crop((left, Y1, left + WIDTH, Y2))

        mask = land_mask(tile)
        pts = pick(distance_inside(mask), WANT, apart=min(tile.size) * 0.17)
        anchors[terrain] = pts

        big = tile.resize((tile.width * SCALE, tile.height * SCALE), Image.LANCZOS)
        big = big.filter(ImageFilter.UnsharpMask(radius=2.4, percent=62, threshold=3))
        sizes[terrain] = (big.width, big.height)
        print(f"  {terrain:7} {TITLES[terrain]:12} {big.width}x{big.height}  "
              f"{len(pts)} places on land")
        if args.write:
            os.makedirs(OUT, exist_ok=True)
            big.save(os.path.join(OUT, terrain + ".webp"), "WEBP", quality=86)

    if args.write:
        mod = os.path.join(ROOT, "apps", "web", "src", "journey", "realmPlates.ts")
        with open(mod, "w") as fh:
            fh.write("/* Generated by tools/make_realms.py. Do not edit.\n"
                     " *\n"
                     " * One island plate per land, cut from the design board,\n"
                     " * and the points on each that are furthest from water.\n"
                     " * The anchors are percentages OF THE PLATE, so the frame\n"
                     " * showing one must carry its aspect ratio.\n"
                     " */\n"
                     "export interface RealmPlate {\n"
                     "  w: number\n  h: number\n"
                     "  /** Deepest-inland points, furthest first. */\n"
                     "  spots: [number, number][]\n}\n\n"
                     "export const REALM_PLATE: Record<string, RealmPlate> = {\n")
            for terrain in ORDER:
                w, h = sizes[terrain]
                pts = ", ".join(f"[{x}, {y}]" for x, y in anchors[terrain])
                fh.write(f"  {terrain}: {{ w: {w}, h: {h}, spots: [{pts}] }},\n")
            fh.write("}\n")
        print(f"\n  wrote apps/web/src/journey/realmPlates.ts")
    else:
        print("\nDRY RUN - nothing written. Re-run with --write.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
