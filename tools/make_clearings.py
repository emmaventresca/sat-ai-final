#!/usr/bin/env python3
"""Crop the site plates down to the artwork a student actually stands in.

The eleven site plates ship as framed map cards: an ornate border, a dark
mat around it, a title cartouche, a compass rose, a legend and a scale bar.
As a level-three backdrop that reads as a card lying on a table rather than
as a place - and roughly a third of the file is mat, so markers authored in
0-100 space land on the padding instead of on the ground.

This crops each plate to the inside of its frame and writes it to
art/clearings/. The originals stay where they are: the inner map still
wants the card, and an irreversible crop of someone's artwork is not a
thing to do in passing.

The mat is found rather than assumed, because the plates do not agree -
most sit at 15%-85% across, The Hollow has no mat at all and Moonlit Lake
has half as much. Found by column variance rather than brightness: the mat
is flat, the artwork is not, and brightness alone calls a dark forest mat.
"""
import argparse, os, sys

import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SITES = os.path.join(ROOT, "apps", "web", "public", "art", "sites")
OUT = os.path.join(ROOT, "apps", "web", "public", "art", "clearings")

# How far inside the detected edge to cut, as a share of the plate. The
# ornate border is about this wide, and leaving a sliver of it looks like a
# mistake where cutting through it looks like a crop.
INSET = 0.012

# Plates that are not cropped site cards but are still used as clearings.
# clearings.ts routes three ocean recognitions to the voyage photographs,
# and the frame showing one still has to carry its aspect ratio - so their
# sizes are measured here rather than left out of the manifest.
EXTRA = [
    ("the-storm", "voyage/the-storm"),
    ("the-home-harbour", "voyage/the-home-harbour"),
    ("the-narrow-strait", "voyage/the-narrow-strait"),
]


def bounds(path: str) -> tuple[float, float, float, float]:
    im = Image.open(path).convert("L")
    a = np.asarray(im, dtype=float)
    # Variance down each column and across each row. Mat is flat.
    cv = a.var(axis=0)
    rv = a.var(axis=1)
    cx = cv > cv.max() * 0.10
    rx = rv > rv.max() * 0.10
    xs = np.where(cx)[0]
    ys = np.where(rx)[0]
    if not len(xs) or not len(ys):
        return 0.0, 1.0, 0.0, 1.0
    return (xs[0] / im.width, (xs[-1] + 1) / im.width,
            ys[0] / im.height, (ys[-1] + 1) / im.height)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--quality", type=int, default=82)
    args = ap.parse_args()

    if args.write:
        os.makedirs(OUT, exist_ok=True)
    sizes: dict[str, tuple[int, int]] = {}
    plates = sorted(f for f in os.listdir(SITES)
                    if f.endswith(".webp") and "-sm" not in f and "-lg" not in f)
    for name in plates:
        src = os.path.join(SITES, name)
        l, r, t, b = bounds(src)
        im = Image.open(src).convert("RGB")
        li = int((l + INSET) * im.width)
        ri = int((r - INSET) * im.width)
        ti = int((t + INSET * im.width / im.height) * im.height)
        bi = int((b - INSET * im.width / im.height) * im.height)
        crop = im.crop((li, ti, ri, bi))
        kept = (crop.width * crop.height) / (im.width * im.height)
        print(f"  {name[:-5]:20} {im.width}x{im.height} -> "
              f"{crop.width}x{crop.height}  ({kept:.0%} kept)")
        sizes[name[:-5]] = (crop.width, crop.height)
        if args.write:
            crop.save(os.path.join(OUT, name), "WEBP", quality=args.quality)
            small = crop.copy()
            small.thumbnail((1100, 1100), Image.LANCZOS)
            small.save(os.path.join(OUT, name[:-5] + "-sm.webp"), "WEBP",
                       quality=args.quality)
    for slug, rel in EXTRA:
        path = os.path.join(ROOT, "apps", "web", "public", "art", rel + ".webp")
        if os.path.exists(path):
            with Image.open(path) as im:
                sizes[slug] = (im.width, im.height)
            print(f"  {slug:20} (not cropped) {sizes[slug][0]}x{sizes[slug][1]}")
        else:
            print(f"  {slug:20} MISSING at art/{rel}.webp")

    if args.write:
        # The app has to know each plate's shape. Anchors are percentages of
        # the plate, so the frame showing it must have the plate's own
        # aspect ratio - otherwise object-fit crops the picture and every
        # authored coordinate quietly points somewhere else. The crops are
        # not all the same shape (The Hollow is 1.74, Cedar Lake is 1.13),
        # so this is measured and written out rather than assumed.
        mod = os.path.join(ROOT, "apps", "web", "src", "journey",
                           "clearingSizes.ts")
        with open(mod, "w") as fh:
            fh.write("/* Generated by tools/make_clearings.py. Do not edit.\n"
                     " *\n"
                     " * The cropped size of each clearing plate. The frame\n"
                     " * that shows one must match its aspect ratio, because\n"
                     " * the anchors in clearings.ts are percentages OF THE\n"
                     " * PLATE - crop the picture and every one of them moves.\n"
                     " */\n"
                     "export const CLEARING_SIZE:"
                     " Record<string, { w: number; h: number }> = {\n")
            for slug, (w, h) in sorted(sizes.items()):
                fh.write(f"  '{slug}': {{ w: {w}, h: {h} }},\n")
            fh.write("}\n")
        print(f"\n  wrote {os.path.relpath(mod, ROOT)}")
    if not args.write:
        print("\nDRY RUN - nothing written. Re-run with --write.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
